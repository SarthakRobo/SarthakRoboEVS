import os

with open("app.py", "a", encoding="utf-8") as f:
    f.write("\n")
    f.write("# === ENGLISH TEACHER ROUTE ===\n")
    f.write("@app.route('/get_english_slide/<int:slide_id>')\n")
    f.write("def get_english_slide(slide_id):\n")
    f.write("    english_slides = []\n")
    f.write("    if os.path.exists('english_data.txt'):\n")
    f.write("        with open('english_data.txt', 'r', encoding='utf-8') as file:\n")
    f.write("            lines = file.readlines()\n")
    f.write("            for i, line in enumerate(lines):\n")
    f.write("                line = line.strip()\n")
    f.write("                if line:\n")
    f.write("                    # Q aur A ko alag karne ke liye 'Answer:' ka use\n")
    f.write("                    if 'Answer:' in line:\n")
    f.write("                        parts = line.split('Answer:')\n")
    f.write("                        q_text = parts[0].strip()\n")
    f.write("                        a_text = parts[1].strip()\n")
    f.write("                    else:\n")
    f.write("                        q_text = line\n")
    f.write("                        a_text = ''\n")
    f.write("                    english_slides.append({\n")
    f.write("                        'id': i+1,\n")
    f.write("                        'is_heading': False,\n")
    f.write("                        'question': q_text,\n")
    f.write("                        'answer': a_text,\n")
    f.write("                        'audio': f'/static/audios/english_slide_{i+1}.mp3'\n")
    f.write("                    })\n")
    f.write("    \n")
    f.write("    for slide in english_slides:\n")
    f.write("        if slide['id'] == slide_id:\n")
    f.write("            return jsonify(slide)\n")
    f.write("    return jsonify({'error': 'Slide not found'})\n")

print("✅ English Route fix ho gaya!")
